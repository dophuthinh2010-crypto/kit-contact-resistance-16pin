"""CR-TEST jack boards (female = RS16P-T socket, male = RP16-T plug), rev B.

Each contact pad n goes to IDC pin 2n-1 (force) and 2n (sense). Both are the same copper net,
C<n>; the Kelvin split is done by layout: the force and sense traces leave the pad on opposite
sides and only meet at the pad. Pins 33/34 are not connected (rev B).
Run:  python jack_board.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import kgen  # noqa: E402
from kgen import Part  # noqa: E402
from lib import F_IDC34, F_PLUG, F_SOCKET, S_IDC34, S_PLUG, S_SOCKET  # noqa: E402

REV, DATE = "B", "2026-11-19"
W, H = 80.0, 40.0
HOLES = [(3.5, 3.5), (76.5, 3.5), (3.5, 36.5), (76.5, 36.5)]


def build(kind):
    female = kind == "female"
    project = f"crkit_jack_{kind}"
    out = os.path.join(os.path.dirname(__file__), "..", "..", "kicad", project)
    os.makedirs(out, exist_ok=True)
    jack = Part("J1", "RS16P-T socket" if female else "RP16-T plug", S_SOCKET if female else S_PLUG, F_SOCKET if female else F_PLUG,
                {str(n): f"C{n}" for n in range(1, 17)}, mpn="ITW McMurdo RS16P-T" if female else "ITW McMurdo RP16-T",
                note="device under test, plate on M3 standoffs (7.9 mm socket / 7.1 mm plug)", block="Jack",
                pcb=(40, 14, 0))
    idc = {str(2 * n - 1): f"C{n}" for n in range(1, 17)}
    idc.update({str(2 * n): f"C{n}" for n in range(1, 17)})
    idc.update({"33": None, "34": None})
    hdr = Part("J2", "To main board " + ("J2" if female else "J3"), S_IDC34, F_IDC34, idc, mpn="Amphenol T821134A1S100CEU",
               note="odd = force n, even = sense n (Kelvin at the pad)", block="Jack", pcb=(40 - 8 * 2.54, 31, 0))
    parts = [jack, hdr]
    jack.sch, hdr.sch = (90, 80), (170, 80)
    blocks = [dict(name=f"Jack board ({kind})", rect=(30, 40, 240, 140),
                   text="Contact n -> IDC 2n-1 (force) and 2n (sense). Route the two traces from opposite sides of the pad.")]
    sch = os.path.join(out, project + ".kicad_sch")
    kgen.write_schematic(sch, project, parts, blocks, f"CR-TEST jack board, {kind}", REV, DATE,
                         ["Generated by hardware/scripts/kicad_gen/jack_board.py"], paper="A4")
    pcb = os.path.join(out, project + ".kicad_pcb")
    kgen.write_board(pcb, project, parts, (W, H), holes=HOLES, title=f"CR-TEST jack board {kind}", rev=REV, date=DATE,
                     zones=[dict(net="C1", layer="F.Cu", pts=[(0, 0), (0.1, 0), (0.1, 0.1)])][:0],
                     texts=[(5, 27.5, f"CR-TEST {kind.upper()} rev B", 1.0), (5, 38.6, "Kelvin: force and sense leave each pad on opposite sides", 0.7)])
    kgen.write_project(os.path.join(out, project + ".kicad_pro"), project,
                       [dict(name="Kelvin", track_width=0.6, clearance=0.25)], [("C*", "Kelvin")])
    kgen.check_sexpr(sch)
    kgen.check_sexpr(pcb)
    bad = kgen.overlaps(parts)
    print(project, "overlaps:", bad or "none")
    return parts


if __name__ == "__main__":
    for k in ("female", "male"):
        build(k)
